# =============================================================================
# purpose:  GitHub OAuth 2.0 authentication for single personal-use instance.
#           Flow:
#             1. Frontend requests login URL  → GET /auth/login
#             2. User authenticates on GitHub → GitHub redirects to /auth/callback
#             3. Backend exchanges code for GitHub token → verifies username
#             4. If username == allowed_github_username → issues own JWT pair
#             5. Refresh token stored in Redis (TTL = 30 days), rotated on use
#
#           No roles. No RBAC. One user. Authenticated = full access.
# =============================================================================

import logging
import secrets
import uuid
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from typing import Any

import httpx
from jose import JWTError, jwt
from jose.exceptions import ExpiredSignatureError
from redis.asyncio import Redis
from redis.exceptions import RedisError

from app.core.config import get_settings
from app.core.exceptions import AuthTokenInvalidError, AuthTokenMissingError

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Redis key patterns for token storage
# ---------------------------------------------------------------------------
REFRESH_TOKEN_KEY_PREFIX = "lms:auth:refresh:"   # lms:auth:refresh:{jti}
OAUTH_STATE_KEY_PREFIX   = "lms:auth:state:"     # lms:auth:state:{state}
OAUTH_STATE_TTL          = 600                   # 10 minutes — state is short-lived

# GitHub OAuth endpoints
GITHUB_AUTHORIZE_URL  = "https://github.com/login/oauth/authorize"
GITHUB_TOKEN_URL      = "https://github.com/login/oauth/access_token"
GITHUB_USER_API_URL   = "https://api.github.com/user"


@dataclass
class AuthenticatedUser:
    """Represents a verified, authenticated session."""
    github_username: str
    jti: str          # JWT ID — used to look up / revoke refresh token


# ===========================================================================
# Step 1: Build the GitHub authorization URL
# ===========================================================================

async def get_github_authorization_url(redis: Redis) -> str:
    """
    Generates a GitHub OAuth authorization URL with a CSRF state token.

    The state value is stored in Redis for 10 minutes so the callback
    handler can verify it was generated by this server (CSRF protection).

    Returns:
        Full GitHub authorization URL to redirect the user to.
    """
    settings = get_settings()

    # Cryptographically random state for CSRF protection.
    state = secrets.token_urlsafe(32)

    # Store state in Redis — callback will verify it.
    try:
        state_key = f"{OAUTH_STATE_KEY_PREFIX}{state}"
        await redis.set(state_key, "1", ex=OAUTH_STATE_TTL)
    except RedisError as exc:
        logger.error("Failed to store OAuth state in Redis: %s", exc)
        raise

    params = {
        "client_id":    settings.github_client_id,
        "redirect_uri": settings.github_redirect_uri,
        "scope":        "read:user",
        "state":        state,
    }
    query = "&".join(f"{k}={v}" for k, v in params.items())
    return f"{GITHUB_AUTHORIZE_URL}?{query}"


# ===========================================================================
# Step 2: Exchange code for GitHub token, verify username
# ===========================================================================

async def _exchange_code_for_github_token(code: str) -> str:
    """
    POSTs the authorization code to GitHub and returns the GitHub access token.

    Raises:
        AuthTokenInvalidError if GitHub rejects the code.
    """
    settings = get_settings()

    async with httpx.AsyncClient(timeout=15.0) as client:
        response = await client.post(
            GITHUB_TOKEN_URL,
            headers={"Accept": "application/json"},
            data={
                "client_id":     settings.github_client_id,
                "client_secret": settings.github_client_secret,
                "code":          code,
                "redirect_uri":  settings.github_redirect_uri,
            },
        )

    if response.status_code != 200:
        raise AuthTokenInvalidError(
            f"GitHub token exchange failed (HTTP {response.status_code})."
        )

    data = response.json()

    if "error" in data:
        raise AuthTokenInvalidError(
            f"GitHub OAuth error: {data.get('error_description', data['error'])}"
        )

    github_token = data.get("access_token")
    if not github_token:
        raise AuthTokenInvalidError("GitHub did not return an access token.")

    return github_token


async def _get_github_username(github_access_token: str) -> str:
    """
    Calls GitHub's /user API with the access token and returns the username.

    Raises:
        AuthTokenInvalidError if the API call fails.
    """
    async with httpx.AsyncClient(timeout=10.0) as client:
        response = await client.get(
            GITHUB_USER_API_URL,
            headers={
                "Authorization": f"Bearer {github_access_token}",
                "Accept": "application/vnd.github+json",
            },
        )

    if response.status_code != 200:
        raise AuthTokenInvalidError(
            f"GitHub user API call failed (HTTP {response.status_code})."
        )

    data = response.json()
    username = data.get("login")
    if not username:
        raise AuthTokenInvalidError("GitHub user API did not return a username.")

    return username


async def handle_oauth_callback(
    code: str,
    state: str,
    redis: Redis,
) -> tuple[str, str]:
    """
    Handles the GitHub OAuth callback. Full flow:
      1. Verify state token (CSRF check).
      2. Exchange code for GitHub access token.
      3. Fetch GitHub username.
      4. Verify username == allowed_github_username.
      5. Issue our own access token + refresh token.
      6. Store refresh token in Redis.

    Args:
        code:  Authorization code from GitHub.
        state: State parameter from GitHub (must match what we stored).
        redis: Redis client.

    Returns:
        Tuple of (access_token, refresh_token).

    Raises:
        AuthTokenInvalidError on any failure.
    """
    settings = get_settings()

    # Step 1: Verify state (CSRF protection).
    state_key = f"{OAUTH_STATE_KEY_PREFIX}{state}"
    try:
        stored = await redis.get(state_key)
        if not stored:
            raise AuthTokenInvalidError(
                "Invalid or expired OAuth state. Please start the login flow again."
            )
        # Delete state immediately — single use.
        await redis.delete(state_key)
    except RedisError as exc:
        logger.error("Redis error verifying OAuth state: %s", exc)
        raise AuthTokenInvalidError("Could not verify OAuth state. Please retry.")

    # Step 2: Exchange code for GitHub token.
    github_token = await _exchange_code_for_github_token(code)

    # Step 3: Get GitHub username.
    github_username = await _get_github_username(github_token)

    # Step 4: Enforce single-user policy.
    allowed = settings.allowed_github_username
    if github_username.lower() != allowed.lower():
        logger.warning(
            "Login attempt by unauthorized GitHub user: %s (allowed: %s)",
            github_username,
            allowed,
        )
        raise AuthTokenInvalidError(
            f"GitHub account '{github_username}' is not authorized to use this system."
        )

    logger.info("GitHub OAuth login successful for user: %s", github_username)

    # Step 5 & 6: Issue tokens and store refresh token.
    jti = str(uuid.uuid4())
    access_token = _create_access_token(github_username, jti)
    refresh_token = await _create_and_store_refresh_token(
        redis, github_username, jti
    )

    return access_token, refresh_token


# ===========================================================================
# Token creation and storage
# ===========================================================================

def _create_access_token(github_username: str, jti: str) -> str:
    """
    Issues a short-lived HS256 access token.

    Payload:
        sub  — GitHub username
        jti  — JWT ID (links to refresh token in Redis)
        type — "access"
    """
    settings = get_settings()
    now = datetime.now(timezone.utc)
    exp = now + timedelta(minutes=settings.access_token_expire_minutes)

    payload = {
        "sub":  github_username,
        "jti":  jti,
        "type": "access",
        "iat":  int(now.timestamp()),
        "exp":  int(exp.timestamp()),
    }
    return jwt.encode(payload, settings.jwt_secret_key, algorithm="HS256")


async def _create_and_store_refresh_token(
    redis: Redis,
    github_username: str,
    jti: str,
) -> str:
    """
    Creates a refresh token and stores it securely in Redis.

    The refresh token itself is a random opaque string (not a JWT) stored
    in Redis under lms:auth:refresh:{jti}. The JTI is embedded in the access
    token — this links the access/refresh pair without exposing the refresh
    token value in the JWT.

    TTL = REFRESH_TOKEN_EXPIRE_DAYS.
    """
    settings = get_settings()
    refresh_token = secrets.token_urlsafe(48)

    key = f"{REFRESH_TOKEN_KEY_PREFIX}{jti}"
    ttl_seconds = settings.refresh_token_expire_days * 86400

    try:
        await redis.set(
            key,
            f"{github_username}:{refresh_token}",
            ex=ttl_seconds,
        )
    except RedisError as exc:
        logger.error("Failed to store refresh token in Redis: %s", exc)
        raise AuthTokenInvalidError("Could not create session. Please try again.")

    return refresh_token


async def refresh_access_token(
    refresh_token: str,
    jti: str,
    redis: Redis,
) -> tuple[str, str]:
    """
    Validates a refresh token and issues a new access token + refresh token.
    Implements refresh token rotation — old refresh token is deleted on use.

    Args:
        refresh_token: The opaque refresh token string from the client.
        jti:           The JTI from the (possibly expired) access token.
        redis:         Redis client.

    Returns:
        Tuple of (new_access_token, new_refresh_token).

    Raises:
        AuthTokenInvalidError if the refresh token is invalid or expired.
    """
    key = f"{REFRESH_TOKEN_KEY_PREFIX}{jti}"

    try:
        stored = await redis.get(key)
    except RedisError:
        raise AuthTokenInvalidError("Session store unavailable. Please log in again.")

    if not stored:
        raise AuthTokenInvalidError("Refresh token has expired or been revoked. Please log in again.")

    # Stored value format: "{github_username}:{refresh_token}"
    parts = stored.split(":", 1)
    if len(parts) != 2 or parts[1] != refresh_token:
        raise AuthTokenInvalidError("Invalid refresh token.")

    github_username = parts[0]

    # Delete old refresh token immediately (rotation — prevents reuse).
    await redis.delete(key)

    # Issue new token pair with a fresh JTI.
    new_jti = str(uuid.uuid4())
    new_access_token = _create_access_token(github_username, new_jti)
    new_refresh_token = await _create_and_store_refresh_token(
        redis, github_username, new_jti
    )

    logger.info("Refresh token rotated for user: %s", github_username)
    return new_access_token, new_refresh_token


async def revoke_session(jti: str, redis: Redis) -> None:
    """
    Revokes a session by deleting the refresh token from Redis.
    Called on logout.
    """
    key = f"{REFRESH_TOKEN_KEY_PREFIX}{jti}"
    try:
        await redis.delete(key)
        logger.info("Session revoked (jti=%s)", jti)
    except RedisError as exc:
        logger.warning("Failed to revoke session in Redis: %s", exc)


# ===========================================================================
# Token validation (for request middleware)
# ===========================================================================

def decode_access_token(token: str) -> AuthenticatedUser:
    """
    Decodes and validates our own HS256 access token.

    Returns:
        AuthenticatedUser with github_username and jti.

    Raises:
        AuthTokenInvalidError on any failure.
    """
    settings = get_settings()
    try:
        payload = jwt.decode(
            token,
            settings.jwt_secret_key,
            algorithms=["HS256"],
            options={"verify_exp": True},
        )
    except ExpiredSignatureError:
        raise AuthTokenInvalidError("Access token has expired. Please refresh.")
    except JWTError as exc:
        raise AuthTokenInvalidError(f"Invalid access token: {exc}")

    if payload.get("type") != "access":
        raise AuthTokenInvalidError("Token is not an access token.")

    username = payload.get("sub", "")
    jti = payload.get("jti", "")

    if not username or not jti:
        raise AuthTokenInvalidError("Access token is missing required claims.")

    return AuthenticatedUser(github_username=username, jti=jti)


def extract_bearer_token(authorization_header: str | None) -> str:
    """Extracts the raw token string from 'Bearer <token>' header."""
    if not authorization_header:
        raise AuthTokenMissingError()
    parts = authorization_header.strip().split(" ", 1)
    if len(parts) != 2 or parts[0].lower() != "bearer" or not parts[1]:
        raise AuthTokenInvalidError(
            "Authorization header must be: 'Bearer <token>'"
        )
    return parts[1]
